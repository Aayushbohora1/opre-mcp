/**
 * Generated project index (`README.md` at the project root).
 *
 * It is the one file a human or an agent should open first: what the target is,
 * how far the project has progressed, and where everything else lives. The block
 * is marker-delimited, so hand-written notes above or below it survive.
 */

import { nowIso } from '../core/ids.js';
import { upsertGeneratedSection } from '../core/markdown.js';
import { readFeatures } from '../knowledge/store.js';
import { readPlan, taskProgress } from '../planning/store.js';
import { readFindings, readPages } from '../research/store.js';
import { readRuns } from '../validation/store.js';
import type { ProjectPaths } from './paths.js';
import type { ProjectManifest } from './types.js';

export interface ProjectIndexInput {
  manifest: ProjectManifest;
  stage: string;
  counts: {
    pages: number;
    findings: number;
    features: number;
    tasks: number;
    validationRuns: number;
  };
  tasks: Record<string, number>;
  nextTask: { id: string; title: string } | null;
  recommendedAction: string;
  lastValidation: { status: string; finishedAt: string } | null;
}

export async function writeProjectIndex(
  paths: ProjectPaths,
  input: ProjectIndexInput,
): Promise<void> {
  await upsertGeneratedSection(paths.readme, render(input));
}

/**
 * Rebuilds the project index from the current state. Called after any step that
 * changes the project's shape (creation, research, planning, build, validation).
 */
export async function refreshProjectIndex(
  paths: ProjectPaths,
  manifest: ProjectManifest,
): Promise<void> {
  const [features, tasks, pages, findings, runs] = await Promise.all([
    readFeatures(paths),
    readPlan(paths).then((plan) => plan.tasks),
    readPages(paths),
    readFindings(paths),
    readRuns(paths),
  ]);

  const open = tasks.filter((task) => task.status === 'pending' || task.status === 'in_progress');
  const nextTask = [...open].sort((a, b) => a.priority - b.priority)[0];
  const stage = deriveStage({ pages: pages.length, tasks: tasks.length, openTasks: open.length });
  const failedRuns = runs.filter((run) => run.status !== 'passed').length;
  const lastRun = runs.at(-1);

  await writeProjectIndex(paths, {
    manifest,
    stage,
    counts: {
      pages: pages.length,
      findings: findings.length,
      features: features.length,
      tasks: tasks.length,
      validationRuns: runs.length,
    },
    tasks: taskProgress(tasks),
    nextTask: nextTask === undefined ? null : { id: nextTask.id, title: nextTask.title },
    recommendedAction: recommend(stage, failedRuns),
    lastValidation:
      lastRun === undefined ? null : { status: lastRun.status, finishedAt: lastRun.finishedAt },
  });
}

/**
 * The single source of truth for "where is this project", used by both the
 * generated README index and `opre.get_project_status`.
 */
export function deriveStage(counts: {
  pages: number;
  tasks: number;
  openTasks: number;
}): 'research' | 'planning' | 'building' | 'complete' {
  if (counts.tasks === 0) {
    return counts.pages === 0 ? 'research' : 'planning';
  }
  return counts.openTasks === 0 ? 'complete' : 'building';
}

function recommend(stage: string, failedRuns: number): string {
  if (failedRuns > 0) {
    return 'Inspect `opre.get_validation_report`, fix the recorded gaps, then rerun validation.';
  }
  switch (stage) {
    case 'research':
      return 'Run `opre.start_research`, then `opre.get_research_summary`.';
    case 'planning':
      return 'Run `opre.create_implementation_plan`, then `opre.get_next_task`.';
    case 'building':
      return 'Run `opre.get_next_task`, then `opre.prepare_build_context` for that task.';
    default:
      return 'All tasks are closed; record any residual uncertainty in `knowledge/uncertainties.md`.';
  }
}

function render(input: ProjectIndexInput): string {
  const { manifest, counts, tasks } = input;
  const lines: string[] = [];

  lines.push(`# ${manifest.title}`);
  lines.push('');
  lines.push(`> ${manifest.name} · generated by OPRE ${nowIso()} · stage: **${input.stage}**`);
  lines.push('');
  lines.push(
    `- **Target**: ${manifest.targetType === 'web' ? 'website' : 'application'} <${manifest.target}>`,
  );
  lines.push(`- **Authorisation**: ${manifest.authorisation}`);
  lines.push(`- **Project id**: \`${manifest.id}\``);
  lines.push(`- **Created**: ${manifest.createdAt}`);
  lines.push('');
  lines.push(`## Progress`);
  lines.push('');
  lines.push(
    `| research pages | findings | features | tasks | validation runs |` +
      `\n| --- | --- | --- | --- | --- |` +
      `\n| ${counts.pages} | ${counts.findings} | ${counts.features} | ${counts.tasks} | ${counts.validationRuns} |`,
  );
  lines.push('');
  lines.push(
    `- Tasks: ${
      Object.entries(tasks)
        .filter(([, count]) => count > 0)
        .map(([status, count]) => `${status} ${count}`)
        .join(', ') || 'none yet'
    }`,
  );
  if (input.lastValidation !== null) {
    lines.push(
      `- Last validation: **${input.lastValidation.status}** (${input.lastValidation.finishedAt})`,
    );
  }
  if (input.nextTask !== null) {
    lines.push(`- **Next task**: \`${input.nextTask.id}\` — ${input.nextTask.title}`);
  }
  lines.push('');
  lines.push(`## Layout`);
  lines.push('');
  lines.push('| Path | Contents |');
  lines.push('| --- | --- |');
  lines.push('| `opre.json` | manifest: target, authorisation, runner configuration |');
  lines.push(
    '| `research/` | `report.md`, `architecture.md`, `pages.json`, `findings.json`, `sources.json` |',
  );
  lines.push(
    '| `knowledge/` | `features.json`, `requirements.md`, `decisions.md`, `uncertainties.md`, `workflows/` |',
  );
  lines.push('| `planning/` | `plan.md`, `tasks.json` |');
  lines.push('| `validation/` | `runs.json`, `known-gaps.md` |');
  lines.push('| `artifacts/` | `screenshots/`, `reports/` (build results, optional HAR) |');
  lines.push('| `app/` | the rebuilt application |');
  lines.push('');
  lines.push(`## Next`);
  lines.push('');
  lines.push(input.recommendedAction);
  lines.push('');
  lines.push(
    'Retrieve context through the OPRE tools (`opre.search_knowledge`, `opre.get_feature`, ' +
      '`opre.get_evidence`, `opre.get_document_excerpt`) rather than reading whole files.',
  );
  lines.push('');
  lines.push('## Notes');
  lines.push('');
  lines.push('_Add your own notes here; this section is outside the generated markers._');
  return lines.join('\n');
}
